"""Write ProjectDocs/outline.md: every workbook's chapters and their sections.

The chapter order comes from Chapters/book_01.txt ... book_36.txt, and the
titles come from the \\chapter and \\section commands in each chapter's
en_US/student.tex. Run it from the Build directory after chapters are added,
removed, renamed or reordered:

    python3 make_outline.py
"""

import re
from pathlib import Path

BUILD_DIR = Path(__file__).resolve().parent
ROOT = BUILD_DIR.parent
CHAPTERS = ROOT / "Chapters"
OUTLINE = ROOT / "ProjectDocs" / "outline.md"
VOL_COUNT = 36

INTRO = """\
# Current Outline

This is the current outline. It is not written in stone. As we work,
we continue to find things that should be included. We also find things
that need to be reordered. However, it will give you an idea of where
we intend to go.

The student should already know algebra well and be able to type. At
the end, the student should be ready to do an internship at a tech
company.

The course emphasizes breadth over depth. We believe that most people
learn difficult ideas twice: The first time they are baffled and have
no intuition in the area. The second time, usually when they must
leverage it in the real world or have to teach it to someone else, the
student has the requisite intuition and is able to fully grasp and appreciate
the details.

There are two questions that determine where any topic goes in the order:

1. **Has the student seen what they need to understand this topic?**

   This is the obvious one: Ideas should stack neatly. This is not
   always easy to do. For example, the idea of light is important and
   familiar to the student. Can we talk about light before we talk
   about Maxwell's equations? Sure! We gesture in the direction of
   electromagnetic waves and keep moving. Later, when the student's
   understanding is a little more sophisticated, we can double-back and
   talk about how electromagnetic waves work.

2. **Is a professional engineer/scientist/actuary/programmer more likely
   to remember this idea than the ideas that come later?**

   It is weird when you meet someone who can do differential
   equations, but doesn't know how a submarine adjusts its buoyancy,
   right? Stuff at the beginning of the series should be remembered by
   99% of all technical people. Stuff at the end of the series
   might be remembered by only 40%.

   Not every student will make it through the whole sequence. We
   should make sure the more basic/important stuff is near the beginning.

For the topics that still need to be covered, see the
[topic list](topic_list.md) and the [to-do list](todo.md).

<!-- The rest of this file is generated by Build/make_outline.py from
     Chapters/book_NN.txt and each chapter's \\chapter and \\section titles.
     Do not edit it by hand; change the chapters and rerun the script. -->
"""


def strip_comments(tex):
    """Remove LaTeX comments (an unescaped % to the end of the line)."""
    return re.sub(r"(?<!\\)%.*", "", tex)


def braced_args(tex, command):
    """Yield the brace-delimited argument of every \\command{...} (not \\command*)."""
    for m in re.finditer(r"\\" + command + r"\s*(\[[^\]]*\])?\s*\{", tex):
        depth, i = 1, m.end()
        while i < len(tex) and depth:
            depth += {"{": 1, "}": -1}.get(tex[i], 0)
            i += 1
        yield tex[m.end() : i - 1]


def plain(title):
    """Turn a LaTeX title into Markdown-friendly text. Inline math is kept."""
    title = re.sub(r"\\(index|label)\{[^{}]*(\{[^{}]*\}[^{}]*)*\}", "", title)
    title = re.sub(r"\\texorpdfstring\{((?:[^{}]|\{[^{}]*\})*)\}\{[^{}]*\}", r"\1", title)
    title = re.sub(r"\\mintinline\{[^{}]*\}\{([^{}]*)\}", r"`\1`", title)
    title = re.sub(r"\\(textit|emph|textbf|texttt|text|mbox)\{([^{}]*)\}", r"\2", title)
    title = re.sub(r"\\(pyfunction|pyvar|pytype|filename)\{([^{}]*)\}", r"`\2`", title)
    for a, b in [("``", "“"), ("''", "”"), ("---", "—"), ("--", "–"), ("\\&", "&"),
                 ("\\%", "%"), ("\\_", "_"), ("~", " "), ("\\ ", " "), ("\\'e", "é")]:
        title = title.replace(a, b)
    return " ".join(title.split())


def main():
    out = [INTRO]
    for vol in range(1, VOL_COUNT + 1):
        book = CHAPTERS / f"book_{vol:02d}.txt"
        if not book.exists():
            continue
        ids = [l.strip() for l in book.read_text().splitlines()
               if l.strip() and not l.strip().startswith("#")]
        out.append(f"\n## Workbook {vol}\n")
        for cid in ids:
            tex_path = CHAPTERS / cid / "en_US" / "student.tex"
            if not tex_path.exists():
                out.append(f"* `{cid}`: (missing `student.tex`)")
                continue
            tex = strip_comments(tex_path.read_text())
            chapter = next(braced_args(tex, "chapter"), cid)
            out.append(f"* [{plain(chapter)}](../Chapters/{cid}/en_US/student.tex) (`{cid}`)")
            for section in braced_args(tex, "section"):
                out.append(f"  * {plain(section)}")
    OUTLINE.write_text("\n".join(out) + "\n")
    print(f"Wrote {OUTLINE}")


if __name__ == "__main__":
    main()
